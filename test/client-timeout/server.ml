(* Server for the client timeout tests: server.exe [limit|pool] PORT TLS_PORT.
   It listens both in plain HTTP on PORT and over TLS on TLS_PORT, with a
   self-signed certificate generated by the cram test, and its
   bounds are small so that the tests run fast: a timeout of 2 seconds, a
   keep-alive timeout of 3 seconds and a minimum data rate of 2 bytes per
   second. It is also given a server timeout, which has no effect and should be
   warned about.

   With the argument [limit], it is instead a server that accepts 4
   connections at most per client address. This limit has its own server since
   the other scenarios run at once, all from the same address.

   With the argument [pool], it is instead a server with room for few
   connections: <maxconnected> is 5, and since each of its two listening
   sockets counts for one connection while it waits for a new one, it is full
   at 4 connections. Its timeouts are long enough not to interfere.

   The servers listen on 127.0.0.1 only: a port alone would also listen on
   IPv6, with a socket that counts too, and only where IPv6 is available.

   Its resources:
   - /slow answers after four seconds, longer than the timeout, the way a comet
     request of Eliom waits for an event before answering;
   - /length reads the whole body of the request and answers its length;
   - /big answers 32 MB, more than the socket buffers hold;
   - anything else answers "ok". *)

open Lwt.Infix

let respond body =
  Lwt.return
    (Ocsigen.Extensions.Ext_found
       (fun () ->
         Lwt.return (Ocsigen.Response.respond_string ~status:`OK ~body ())))

let big = lazy (String.make (32 * 1024 * 1024) 'x')

let resources _vh _config_info _path = function
  | Ocsigen.Extensions.Req_found _ ->
      Lwt.return Ocsigen.Extensions.Ext_do_nothing
  | Ocsigen.Extensions.Req_not_found (_, {Ocsigen.Extensions.request_info; _})
    -> (
    match Ocsigen.Request.path request_info with
    | ["slow"] -> Lwt_unix.sleep 4. >>= fun () -> respond "slow response"
    | ["length"] ->
        Cohttp_lwt.Body.to_string (Ocsigen.Request.body request_info)
        >>= fun body -> respond (string_of_int (String.length body))
    | ["big"] -> respond (Lazy.force big)
    | _ -> respond "ok")

let start ~port ~tls_port ~dir ~command_pipe =
  Ocsigen.Server.start
    ~ports:[`IPv4 Unix.inet_addr_loopback, int_of_string port]
    ~ssl_ports:[`IPv4 Unix.inet_addr_loopback, int_of_string tls_port]
    ~ssl_info:
      (Some
         { Ocsigen.Config.ssl_certificate = Some "cert.pem"
         ; ssl_privatekey = Some "privkey.pem"
         ; ssl_ciphers = None
         ; ssl_dhfile = None
         ; ssl_curve = None })
    ~logdir:(Filename.concat dir "log")
    ~uploaddir:None ~usedefaulthostname:true ~command_pipe
    ~default_charset:(Some "utf-8")

let () =
  match Sys.argv with
  | [|_; port; tls_port|] ->
      start ~port ~tls_port ~dir:"." ~command_pipe:"local.cmd" ~client_timeout:2
        ~keepalive_timeout:3 ~min_data_rate:2 ~server_timeout:1
        [Ocsigen.Server.host [resources]]
  | [|_; "limit"; port; tls_port|] ->
      start ~port ~tls_port ~dir:"limit" ~command_pipe:"limit.cmd"
        ~max_connections_per_address:4
        [Ocsigen.Server.host [resources]]
  | [|_; "pool"; port; tls_port|] ->
      start ~port ~tls_port ~dir:"pool" ~command_pipe:"pool.cmd"
        ~max_number_of_connections:5 ~client_timeout:10 ~keepalive_timeout:30
        [Ocsigen.Server.host [resources]]
  | _ -> failwith "usage: server [limit|pool] PORT TLS_PORT"
