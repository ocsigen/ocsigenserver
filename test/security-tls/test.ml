(* F5: the HTTPS server must require TLS 1.2 at minimum. This starts an HTTPS
   listener with a self-signed certificate (generated by the cram test), on
   the port given as argument. The handler is irrelevant: the test only checks
   the TLS handshake. The ciphers lower the OpenSSL security level to 0, which
   alone would allow TLS 1.1, so that only the minimum version can refuse
   it. *)

let respond _vh _config_info _path _request_state =
  Lwt.return
    (Ocsigen.Extensions.Ext_found
       (fun () ->
         Lwt.return
           (Ocsigen.Response.make (Cohttp.Response.make ~status:`OK ()))))

let () =
  let port =
    match Sys.argv with
    | [|_; port|] -> int_of_string port
    | _ -> failwith "usage: test.exe PORT"
  in
  (* Without any HTTP port, the server would listen on port 80. *)
  Ocsigen.Server.start
    ~ports:[`Unix "./local.sock", 0]
    ~ssl_ports:[`IPv4 Unix.inet_addr_loopback, port]
    ~ssl_info:
      (Some
         { Ocsigen.Config.ssl_certificate = Some "cert.pem"
         ; ssl_privatekey = Some "privkey.pem"
         ; ssl_ciphers = Some "DEFAULT:@SECLEVEL=0"
         ; ssl_dhfile = None
         ; ssl_curve = None })
    ~logdir:"log" ~uploaddir:None ~usedefaulthostname:true
    ~command_pipe:"local.cmd" ~default_charset:(Some "utf-8")
    [Ocsigen.Server.host [respond]]
