(* An upstream server for the reverse proxy tests, over HTTP (port 8073) and
   HTTPS (port 8064, with a self-signed certificate generated by the cram
   test). It answers every request with what it received: the path and
   query, as they came, the Host header, whether the connection was secure,
   and the forwarding headers; or, for /headers, all the headers but
   User-Agent, and the body. *)

open Lwt.Infix

let echo _vh _config_info _path = function
  | Ocsigen.Extensions.Req_found _ ->
      Lwt.return Ocsigen.Extensions.Ext_do_nothing
  | Ocsigen.Extensions.Req_not_found (_, {Ocsigen.Extensions.request_info; _})
    ->
      let header name =
        Option.value ~default:"-"
          (Ocsigen.Request.header request_info name)
      in
      let path_and_query =
        let path = Uri.path (Ocsigen.Request.uri request_info) in
        match Ocsigen.Request.query request_info with
        | Some query -> path ^ "?" ^ query
        | None -> path
      in
      let body () =
        match Ocsigen.Request.path request_info with
        | [ "headers" ] ->
            Cohttp_lwt.Body.to_string (Ocsigen.Request.body request_info)
            >|= fun body ->
            (Ocsigen.Request.to_cohttp request_info
            |> Cohttp.Request.headers |> Cohttp.Header.to_list
            |> List.filter_map (fun (name, value) ->
                   match String.lowercase_ascii name with
                   | "user-agent" -> None
                   | name -> Some (name ^ ": " ^ value ^ "\n"))
            |> List.sort compare |> String.concat "")
            ^ "body: " ^ body ^ "\n"
        | _ ->
            Lwt.return
              (Printf.sprintf
                 "path: %s\nhost: %s\nhttps: %b\n\
                  x-forwarded-proto: %s\nx-forwarded-for: %s\n"
                 path_and_query
                 (header Ocsigen_http.Header.Name.host)
                 (Ocsigen.Request.ssl request_info)
                 (header Ocsigen_http.Header.Name.x_forwarded_proto)
                 (header Ocsigen_http.Header.Name.x_forwarded_for))
      in
      Lwt.return
        (Ocsigen.Extensions.Ext_found
           (fun () ->
             body () >|= fun body ->
             Ocsigen.Response.respond_string ~status:`OK ~body ()))

let () =
  Ocsigen.Server.start
    ~ports:[ (`All, 8073) ]
    ~ssl_ports:[ (`All, 8064) ]
    ~ssl_info:
      (Some
         { Ocsigen.Config.ssl_certificate = Some "cert.pem"
         ; ssl_privatekey = Some "privkey.pem"
         ; ssl_ciphers = None
         ; ssl_dhfile = None
         ; ssl_curve = None })
    ~logdir:"log" ~datadir:"data" ~uploaddir:None ~usedefaulthostname:true
    ~command_pipe:"local.cmd"
    [ Ocsigen.Server.host [ echo ] ]
